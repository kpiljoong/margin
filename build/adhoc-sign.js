'use strict';
// Release builds are not signed with a Developer ID. On Apple Silicon a
// downloaded app whose signature doesn't cover the whole bundle is reported as
// "damaged", so give the packaged app a complete ad-hoc signature before the
// dmg is made.
const { execFileSync } = require('node:child_process');
const path = require('node:path');

exports.default = async function adhocSign(context) {
  if (context.electronPlatformName !== 'darwin') return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'inherit' });
  execFileSync('codesign', ['--verify', '--deep', '--strict', app], { stdio: 'inherit' });
};
